export const getAirlineLogoUrl = (nameOrCarrier?: string, code?: string): string | undefined => {
  const cleanName = (nameOrCarrier || '').trim().toLowerCase();
  const cleanCode = (code || '').trim().toUpperCase();

  const byExact = AFRICAN_AIRLINE_DIRECTORY.find(
    (entry) =>
      (cleanName && entry.name.toLowerCase() === cleanName) ||
      (cleanCode && entry.code.toUpperCase() === cleanCode)
  );
  if (byExact) return byExact.logoUrl;

  if (cleanName) {
    const byPartial = AFRICAN_AIRLINE_DIRECTORY.find(
      (entry) =>
        cleanName.includes(entry.name.toLowerCase()) ||
        entry.name.toLowerCase().includes(cleanName)
    );
    if (byPartial) return byPartial.logoUrl;
  }
  return undefined;
};

